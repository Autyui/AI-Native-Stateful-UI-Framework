def _copy_template_assets(target_ui_dir: Path) -> Optional[Path]:
    if not _TEMPLATE_ASSETS_DIR.exists():
        return None
    target_assets_dir = target_ui_dir / "assets"
    for src in _TEMPLATE_ASSETS_DIR.rglob("*"):
        rel = src.relative_to(_TEMPLATE_ASSETS_DIR)
        dst = target_assets_dir / rel
        if src.is_dir():
            dst.mkdir(parents=True, exist_ok=True)
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        # Keep user-customized runtime backgrounds if they already exist.
        if dst.exists():
            continue
        shutil.copy2(src, dst)
    return target_assets_dir


def write_bridge_bundle(
    *,
    target_bridge_dir: Path,
    thread_id: str,
    project_root: Path,
    preview: Dict[str, Any],
) -> Dict[str, str]:
    target_bridge_dir.mkdir(parents=True, exist_ok=True)
    target_ui_dir = target_bridge_dir.parent / "ui"
    target_ui_dir.mkdir(parents=True, exist_ok=True)
    launcher_path = target_bridge_dir / "aui_bridge.py"
    protocol_path = target_bridge_dir / "aui_ui_protocol.json"
    config_path = target_bridge_dir / "aui_bridge_config.json"
    readme_path = target_bridge_dir / "README_BRIDGE.md"
    ui_runner_path = target_ui_dir / "ui_runner.py"
    ui_index_path = target_ui_dir / "index.html"
    ui_readme_path = target_ui_dir / "README_UI.md"

    launch_profile = _safe_dict(preview.get("launch_profile"))
    config = _build_bridge_config(
        thread_id=thread_id,
        project_root=project_root,
        launch_profile=launch_profile,
    )

    launcher_path.write_text(render_bridge_script(), encoding="utf-8")
    protocol_path.write_text(json.dumps(preview.get("ui_protocol") or {}, ensure_ascii=False, indent=2), encoding="utf-8")
    config_path.write_text(json.dumps(config, ensure_ascii=False, indent=2), encoding="utf-8")
    ui_runner_path.write_text(render_ui_runner_script(), encoding="utf-8")
    ui_index_path.write_text(render_embedded_ui_html(), encoding="utf-8")
    copied_assets_dir = _copy_template_assets(target_ui_dir)
    readme_path.write_text(_BRIDGE_README_CONTENT, encoding="utf-8")
    ui_readme_path.write_text(_UI_README_CONTENT, encoding="utf-8")

    result = {
        "launcher_path": str(launcher_path),
        "protocol_path": str(protocol_path),
        "config_path": str(config_path),
        "readme_path": str(readme_path),
        "bridge_dir": str(target_bridge_dir),
        "ui_runner_path": str(ui_runner_path),
        "ui_index_path": str(ui_index_path),
        "ui_readme_path": str(ui_readme_path),
        "ui_dir": str(target_ui_dir),
    }
    if copied_assets_dir is not None:
        result["ui_assets_dir"] = str(copied_assets_dir)
    return result


