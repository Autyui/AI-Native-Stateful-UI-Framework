def _dedupe_keep_order(items: Iterable[str]) -> List[str]:
    seen = set()
    out: List[str] = []
    for item in items:
        key = item.strip()
        if not key or key in seen:
            continue
        seen.add(key)
        out.append(key)
    return out


def _split_command(cmd: str) -> List[str]:
    text = (cmd or "").strip()
    if not text:
        return []
    try:
        return shlex.split(text)
    except Exception:
        return text.split()


def _looks_like_activation_command(line: str) -> bool:
    text = (line or "").strip().strip("\"'")
    low = text.lower()
    if low.startswith("source "):
        tail = text[7:].strip()
        if _POSIX_ACTIVATE_RE.search(tail):
            return True
    if _WINDOWS_ACTIVATE_RE.search(text):
        return True
    if _CONDA_ACTIVATE_RE.fullmatch(text):
        return True
    if low in {"poetry shell", "pipenv shell"}:
        return True
    return False


def _is_setup_command(command: str) -> bool:
    low = (command or "").strip().lower()
    if not low:
        return True
    if _looks_like_activation_command(low):
        return True
    return any(low.startswith(prefix) for prefix in _SETUP_PREFIXES)


def _normalize_venv_dir(raw_path: str) -> str:
    path = (raw_path or "").strip().replace("\\", "/")
    while path.startswith("./"):
        path = path[2:]
    while path.startswith("../"):
        path = path[3:]
    path = path.strip("/")
    if not path:
        return ""
    if "/" in path:
        return path.split("/")[-1]
    return path


def _extract_venv_hint(readme_text: str) -> Dict[str, str]:
    if not readme_text:
        return {}

    def _iter_lines() -> Iterable[str]:
        for block in _CODE_BLOCK_RE.findall(readme_text):
            for raw_line in block.splitlines():
                line = raw_line.strip()
                if line:
                    yield line
        for raw_line in readme_text.splitlines():
            line = raw_line.strip()
            if line.startswith("$ "):
                yield line[2:].strip()

    for line in _iter_lines():
        text = line.strip().strip("\"'")
        low = text.lower()
        if low.startswith("source "):
            tail = text[7:].strip().strip("\"'")
            m = _POSIX_ACTIVATE_RE.search(tail)
            if m:
                venv_dir = _normalize_venv_dir(m.group("path"))
                if venv_dir:
                    return {"type": "venv_path", "venv_dir": venv_dir, "activation_command": line}
        m = _WINDOWS_ACTIVATE_RE.search(text)
        if m:
            venv_dir = _normalize_venv_dir(m.group("path"))
            if venv_dir:
                return {"type": "venv_path", "venv_dir": venv_dir, "activation_command": line}
        m = _CONDA_ACTIVATE_RE.fullmatch(text)
        if m:
            return {"type": "conda", "env_name": m.group("name"), "activation_command": line}
        if low in {"poetry shell", "pipenv shell"}:
            return {"type": "shell_manager", "manager": low.split()[0], "activation_command": line}
    return {}


def _build_pre_run_checklist(
    readme_text: str,
    recommended_command: str,
    venv_hint: Dict[str, str],
) -> List[str]:
    text = readme_text or ""
    low = text.lower()
    items: List[str] = []

    # Always state boundary clearly.
    items.append(
        "AIUI is non-intrusive: it only uses .aui-dashboard files and will not modify your project source files."
    )

    if venv_hint:
        activation = str(venv_hint.get("activation_command") or "").strip()
        if activation:
            items.append(f"Activate environment before run: `{activation}`.")

    if recommended_command:
        items.append(f"Run command from README analysis: `{recommended_command}`.")

    # Lightweight README-derived checks (no auto mutation, only reminders).
    if "github token" in low or "gh token" in low or "gittoken" in low:
        items.append("README mentions GitHub token. Confirm required token env vars are set before run.")
    if "openai_api_key" in low or "api key" in low or "apikey" in low:
        items.append("README mentions API key setup. Confirm required provider keys are configured.")
    if "requirements.txt" in low or "pip install" in low or "npm install" in low or "pnpm install" in low:
        items.append("Dependencies may be required by README. Ensure install steps are completed manually.")
    if "resources" in low and ("mkdir" in low or "directory" in low or "folder" in low or "目录" in text):
        items.append("README appears to require a `resources` directory. Confirm it exists and contains needed input data.")
    if "result" in low and ("directory" in low or "folder" in low or "目录" in text):
        items.append("README references output folder `result`. Confirm output path assumptions before run.")
    if ".env" in low or "environment variable" in low or "环境变量" in text:
        items.append("README references environment variables/.env. Confirm required variables are present.")

    # Try to extract imperative checklist-like lines from README.
    for raw_line in _README_LINE_SPLIT_RE.split(text):
        line = (raw_line or "").strip()
        if not line:
            continue
        l = line.lower()
        if len(items) >= 10:
            break
        # Keep concise high-signal lines only.
        if any(
            kw in l
            for kw in (
                "make sure",
                "ensure",
                "before run",
                "prerequisite",
                "需要先",
                "请先",
                "手动",
                "must",
            )
        ):
            cleaned = line.lstrip("-*0123456789. ").strip()
            if cleaned and len(cleaned) <= 180:
                items.append(cleaned)

    return _dedupe_keep_order(items)


def _extract_commands_from_readme(readme_text: str) -> List[str]:
    if not readme_text:
        return []
    candidates: List[str] = []

    # fenced code block lines
    for block in _CODE_BLOCK_RE.findall(readme_text):
        for raw_line in block.splitlines():
            line = raw_line.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("$ "):
                line = line[2:].strip()
            lower = line.lower()
            if lower.startswith(_COMMAND_STARTERS):
                if not _is_setup_command(line):
                    candidates.append(line)

    # plain lines with "$ command"
    for raw_line in readme_text.splitlines():
        line = raw_line.strip()
        if not line.startswith("$ "):
            continue
        line = line[2:].strip()
        lower = line.lower()
        if lower.startswith(_COMMAND_STARTERS):
            if not _is_setup_command(line):
                candidates.append(line)

    # inline command mentions such as: "run with `python core.py`"
    for m in _PYTHON_CMD_INLINE_RE.finditer(readme_text):
        interpreter = m.group(1)
        script = m.group(2)
        line = f"{interpreter} {script}"
        if not _is_setup_command(line):
            candidates.append(line)

    return _dedupe_keep_order(candidates)


def _commands_from_repo_structure(repo_brief: Dict[str, Any]) -> List[str]:
    names: set[str] = set()
    python_file_paths: List[str] = []
    for it in repo_brief.get("top_level_items") or []:
        if not isinstance(it, dict):
            continue
        name = (it.get("name") or "").strip()
        if name:
            names.add(name.lower())
        if (it.get("type") or "") == "file":
            path = (it.get("path") or name or "").strip()
            if path.lower().endswith(".py") and not path.lower().endswith("__init__.py"):
                python_file_paths.append(path)

    out: List[str] = []
    if "docker-compose.yml" in names or "docker-compose.yaml" in names:
        out.append("docker compose up")
    if "package.json" in names:
        out.extend(["npm run dev", "npm start"])
    if "makefile" in names:
        out.append("make run")
    if "start.sh" in names:
        out.append("bash start.sh")
    if "main.py" in names:
        out.append("python main.py")
    if "app.py" in names:
        out.append("python app.py")
    if "manage.py" in names:
        out.append("python manage.py runserver")
    if "pyproject.toml" in names and "app.py" not in names and "main.py" not in names:
        out.append("python -m app")

    # Generic python entry candidates.
    strong_names = ("core.py", "main.py", "app.py", "run.py", "server.py", "start.py", "cli.py", "manage.py")
    lower_paths = [p.lower() for p in python_file_paths]
    for n in strong_names:
        for i, p in enumerate(lower_paths):
            if p == n:
                out.append(f"python {python_file_paths[i]}")

    uniq_python = _dedupe_keep_order(python_file_paths)
    if len(uniq_python) == 1:
        out.append(f"python {uniq_python[0]}")
    for p in sorted(uniq_python, key=lambda x: (x.count("/"), x.count("\\"), len(x)))[:5]:
        out.append(f"python {p}")

    return _dedupe_keep_order(out)


def _choose_recommended_command(readme_commands: List[str], structure_commands: List[str]) -> Tuple[str, List[str]]:
    # Priority rule:
    # 1) README explicit run commands (in source order)
    # 2) Top-level structure heuristic
    # 3) Fallback
    if readme_commands:
        candidates = _dedupe_keep_order([*readme_commands, *structure_commands, "python main.py"])
        return readme_commands[0], candidates
    if structure_commands:
        candidates = _dedupe_keep_order([*structure_commands, "python main.py"])
        return structure_commands[0], candidates
    return "python main.py", ["python main.py"]


def _normalize_flag_value(raw_value: Optional[str]) -> Any:
    if raw_value is None:
        return True
    txt = raw_value.strip()
    if not txt:
        return True
    low = txt.lower()
    if low in {"true", "false"}:
        return low == "true"
    if re.fullmatch(r"\d+", txt):
        try:
            return int(txt)
        except Exception:
            return txt
    if re.fullmatch(r"\d+\.\d+", txt):
        try:
            return float(txt)
        except Exception:
            return txt
    return txt.strip("\"'")


def _extract_flag_defaults(command: str) -> Dict[str, Any]:
    defaults: Dict[str, Any] = {}
    for name, value in _FLAG_RE.findall(command or ""):
        key = name.replace("-", "_").strip()
        if not key:
            continue
        defaults[key] = _normalize_flag_value(value)
    return defaults


def _control_type(name: str, default: Any) -> str:
    low = (name or "").lower()
    if isinstance(default, bool):
        return "switch"
    if any(k in low for k in ("port", "workers", "batch", "steps", "epochs", "num", "size")):
        return "number"
    if isinstance(default, (int, float)):
        return "number"
    return "text"


def _build_controls(flag_defaults: Dict[str, Any]) -> List[Dict[str, Any]]:
    controls: List[Dict[str, Any]] = []
    for key, default in flag_defaults.items():
        controls.append(
            {
                "id": key,
                "label": key.replace("_", " ").title(),
                "type": _control_type(key, default),
                "flag": f"--{key.replace('_', '-')}",
                "default": default,
                "source": "launch_command",
            }
        )
    return controls


def _build_launch_profile(command: str) -> Dict[str, Any]:
    cmd_tokens = _split_command(command)
    command_base: List[str] = []
    if cmd_tokens:
        for tok in cmd_tokens:
            if tok.startswith("--"):
                break
            command_base.append(tok)
    return {
        "command_base": command_base,
        "passthrough_args": [],
        "flag_defaults": _extract_flag_defaults(command),
    }


def _safe_dict(value: Any) -> Dict[str, Any]:
    return value if isinstance(value, dict) else {}


def _safe_list_of_text(values: Any) -> List[str]:
    if not isinstance(values, list):
        return []
    return [str(x) for x in values]


def _build_launch_metadata(
    *,
    command: str,
    candidate_commands: Optional[List[str]] = None,
    working_dir: str = _DEFAULT_WORKING_DIR,
    venv_hint: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    profile = _build_launch_profile(command)
    flag_defaults = profile["flag_defaults"]
    return {
        "launch_profile": {
            "recommended_command": command,
            "candidate_commands": _dedupe_keep_order(candidate_commands or [command]),
            "command_base": profile["command_base"],
            "passthrough_args": profile["passthrough_args"],
            "flag_defaults": flag_defaults,
            "working_dir": working_dir,
            "venv_hint": _safe_dict(venv_hint),
        },
        "controls": _build_controls(flag_defaults),
        "launch": {
            "command": command,
            "working_dir": working_dir,
            "supports_stdin": True,
        },
    }


