def apply_launch_command_override(preview: Dict[str, Any], override_command: str) -> Dict[str, Any]:
    text = (override_command or "").strip()
    if not text:
        return preview

    updated = deepcopy(preview)

    launch_profile = _safe_dict(updated.get("launch_profile"))
    deduped_candidates = _dedupe_keep_order([text, *_safe_list_of_text(launch_profile.get("candidate_commands"))])
    launch_meta = _build_launch_metadata(
        command=text,
        candidate_commands=deduped_candidates,
        working_dir=str(launch_profile.get("working_dir") or _DEFAULT_WORKING_DIR),
        venv_hint=_safe_dict(launch_profile.get("venv_hint")),
    )
    updated["launch_profile"] = launch_meta["launch_profile"]

    ui_protocol = _safe_dict(updated.get("ui_protocol"))
    ui_protocol["controls"] = launch_meta["controls"]
    launch_cfg = _safe_dict(ui_protocol.get("launch"))
    supports_stdin = bool(launch_cfg.get("supports_stdin", True))
    launch_cfg.update(launch_meta["launch"])
    launch_cfg["supports_stdin"] = supports_stdin
    ui_protocol["launch"] = launch_cfg
    updated["ui_protocol"] = ui_protocol
    return updated


